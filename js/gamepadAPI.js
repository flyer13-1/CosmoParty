/* ==========================================================
   gamepadAPI.js  コントローラ + 選択人数 + ログイン状態の共通管理
   ES Module（export 形式）。グローバル変数は一切作らない。

   【設計メモ】
   ・使う側でループさせ、フレームの頭で poll() を「1回だけ」呼ぶ。
     （1フレームに2回呼ぶと、押した瞬間の判定が消えるので注意）
   ・ページが変わると JS の変数は消えるので、Pごとの状態と選択人数は
     sessionStorage に保存し、読み込み時に復元する。
   ・パスワードは保存しない。ログイン後に持つのは name と tok だけ。
     tok が null の人は guest 扱い。（仮）
   ・p は 0始まり（0 = 1P, 1 = 2P, 2 = 3P, 3 = 4P）。
   ========================================================== */
"use strict"; //jsのモード

/* ==========================================================
   ■ 要素の宣言
   ========================================================== */

/* ---- 変数・定数宣言 ---- */
const MAX = 4; // 最大人数
const KEY = "cpty_gp"; // Pごとの記録の sessionStorage キー
const KEYT = "cpty_tar"; // 選択人数の sessionStorage キー
const GST = "guest"; // ゲスト名
const INI = 1; // 選択人数の初期値

let pls = []; // Pごとの記録 [{ idx, id, name, tok }]（init で復元）
let tarPls = INI; // 選択人数（targetPlayers）

/* ==========================================================
   ■ 初期化
   ========================================================== */

/* ----------------------------------------------------------
   init(): 保存してあった状態を復元する（このファイルの読み込み時に1回）
   ---------------------------------------------------------- */
function init() {
  pls = lord(); // Pごとの記録
  tarPls = lodt(); // 選択人数
}
init();

/* ==========================================================
   ■ 共通機能（保存・復元）
   ========================================================== */

/* ----------------------------------------------------------
   c_gp(): 空のP状態を作る（未割り当て・ゲスト）
   ---------------------------------------------------------- */
function c_gp() {
  return { idx: null, id: null, name: GST, tok: null };
}

/* ----------------------------------------------------------
   lord(): sessionStorage から Pごとの記録を復元。
   無い/壊れていれば空の状態を返す
   ---------------------------------------------------------- */
function lord() {
  try {
    const d = JSON.parse(sessionStorage.getItem(KEY));
    if (Array.isArray(d) && d.length === MAX) return d;
  } catch (e) {
    /* 壊れていたら下で作り直す */
    alert("コントローラー情報が読めませんでした。");
    window.console.log("パッド情報ロード不可", e);
  }
  return Array.from({ length: MAX }, c_gp);
}

/* ----------------------------------------------------------
   lodt(): sessionStorage から選択人数を復元。
   無い/範囲外なら初期値 INI
   ---------------------------------------------------------- */
function lodt() {
  const n = Number(sessionStorage.getItem(KEYT)); // 未保存なら null → 0 になる
  return Number.isInteger(n) && n >= 1 && n <= MAX ? n : INI;
}

/* ----------------------------------------------------------
   save(): Pごとの記録を sessionStorage に保存（変更するたびに呼ぶ）
   ---------------------------------------------------------- */
function save() {
  try {
    sessionStorage.setItem(KEY, JSON.stringify(pls));
  } catch (e) {
    /* 保存できなくても画面は動かす */
    alert("パッド情報保存不可。");
    window.console.log("sessionStorage保存不可", e);
  }
}

/* ==========================================================
   ■ コントローラ読み取り機能
   ========================================================== */

/* ---- 機能限定の変数 ---- */
let snp = []; // 最新のコントローラ一覧
let bef = []; // 前フレームのボタン状態 bef[スロット][ボタン番号]
let dwn = []; // 今フレームで「押した瞬間」のボタン dwn[スロット][ボタン番号]
let hld = [];

/* ----------------------------------------------------------
   poll(): 接続済みコントローラの情報 + ボタンの判定
   方向は十字キーでの判定
   使う側のループの「フレームの頭」で、1フレームに1回だけ呼ぶこと。
   ※ ブラウザの仕様で、ボタンを1回押すまで一覧が空のことがある。
   ---------------------------------------------------------- */
function poll() {
  const g = navigator.getGamepads ? navigator.getGamepads() : null;
  snp = g ? Array.from(g) : [];
  hld = [];

  dwn = snp.map((p, i) => {
    if (!p) {
      bef[i] = [];
      hld[i] = [];
      return [];
    }
    const now = p.buttons.map((b) => b.pressed); // 今のボタン状態
    hld[i] = now; // ★追加: 押している間ずっと true

    // 「今は押されている」かつ「前回は押されていない」ものだけ true
    const dn = now.map((v, k) => v && !(bef[i] && bef[i][k]));
    bef[i] = now; // 次のフレームの比較用に保存
    return dn;
  });
  return snp;
}

/* ----------------------------------------------------------
   dn(idx＝pad識別, b＝ボタン識別)
   ---------------------------------------------------------- */
function dn(idx, b = 0) {
  return !!(dwn[idx] && dwn[idx][b]);
}

/* ----------------------------------------------------------
   hold(idx, b): スロット idx のボタン b を、今押している間 true
   b を省略すると 0番（Aボタン）。押し始めだけでなく、押している間ずっと true。
   スロットやボタンが存在しない場合は false（エラーにしない）
   ---------------------------------------------------------- */
function hold(idx, b = 0) {
  return !!(hld[idx] && hld[idx][b]);
}

/* ----------------------------------------------------------
   pad(p): 一つのコントローラ情報を返す。
   ---------------------------------------------------------- */
function pad(p) {
  const s = pls[p];
  if (s.idx === null) return null;
  const g = snp[s.idx];
  return g && g.connected && g.id === s.id ? g : null;
}

/* ----------------------------------------------------------
   live(p): Pのコントローラが今つながっているか（true/false）
   ---------------------------------------------------------- */
function live(p) {
  return pad(p) !== null;
}

/* ==========================================================
   ■ 割り当て機能（誰がどのPか）
   ========================================================== */

/* ----------------------------------------------------------
   who(idx): idx のコントローラの割り当て　なければ-1を返す
   ---------------------------------------------------------- */
function who(idx) {
  const g = snp[idx]; // 最新の写しから取る（poll() 後でないと空）
  if (!g) return -1;
  // idx と id の両方が一致した P を探す（見つからなければ -1）
  return pls.findIndex((s) => s.idx === idx && s.id === g.id);
}

/* ----------------------------------------------------------
   dup(idx): スロット idx のコントローラと同じ機種(id)が、すでにPに登録されていて、
   そのPのコントローラが今つながっていない場合、そのPの番号（0始まり）。無ければ -1
   抜き差しでスロット番号が変わったときに、新しいPを作らず上書きするための判定。
   同じ機種を2台つないでいる場合は、片方が live なので -1（別人として扱う）
   ---------------------------------------------------------- */
function dup(idx) {
  const g = snp[idx];
  if (!g) return -1;
  return pls.findIndex((s, p) => s.idx !== null && s.id === g.id && !live(p));
}

/* ----------------------------------------------------------
   free(): 選択人数の範囲で、最初の空き P（0始まり）。無ければ -1
   隠れている枠(選択人数の外)には入れない
   ---------------------------------------------------------- */
function free() {
  return pls.slice(0, tarPls).findIndex((s) => s.idx === null);
}

/* ----------------------------------------------------------
   asg(p, idx): Pにスロット idx のコントローラを割り当てて保存する
   ---------------------------------------------------------- */
function asg(p, idx) {
  const g = snp[idx]; //特定のコントローラ情報
  if (!g) return false;

  pls[p].idx = idx;
  pls[p].id = g.id;
  save();
  return true;
}

/* ----------------------------------------------------------
   chk(): 割り当て済みなのに、今つながっていないPの番号の配列を返す。
   空配列なら全員OK。→ 「ボタンを押してね」の表示判定に使う
   ---------------------------------------------------------- */
function chk() {
  const out = [];
  pls.forEach((s, p) => {
    if (s.idx !== null && !live(p)) out.push(p);
  });
  return out;
}

/* ----------------------------------------------------------
   rst(p): Pのコントローラ割り当てだけを消す。p を省略すると全員分
   （ログイン情報は消さない）
   ---------------------------------------------------------- */
function rst(p) {
  const f = (s) => {
    s.idx = null;
    s.id = null;
  };
  if (p === undefined) pls.forEach(f);
  else f(pls[p]);
  save();
}

/* ----------------------------------------------------------
   vfy(): sessionStorage に「実際に保存されている内容」を読み直して、
   次のページに渡せる状態か確認する。問題の説明の配列を返す（空なら OK）。
   ※ メモリ上の pls ではなく、保存先を読み直すのが目的
   ---------------------------------------------------------- */
function vfy() {
  const out = []; // 問題の説明を入れていく
  const n = tarPls; // 今の選択人数

  // 人数の保存を確認
  if (Number(sessionStorage.getItem(KEYT)) !== n) {
    out.push("人数が保存されていません");
  }

  // Pごとの記録を、保存先から読み直す
  let d = null;
  try {
    d = JSON.parse(sessionStorage.getItem(KEY));
  } catch (e) {
    /* 壊れている場合は d が null のまま */
  }
  if (!Array.isArray(d) || d.length !== MAX) {
    out.push("コントローラーの記録が読めません");
    return out; // これ以上は調べられない
  }

  // 選択人数ぶんの idx / id を確認
  for (let p = 0; p < n; p++) {
    const s = d[p];
    const okI = s && Number.isInteger(s.idx) && s.idx >= 0; // idx は 0以上の整数
    const okD = s && typeof s.id === "string" && s.id !== ""; // id は空でない文字列
    if (!okI || !okD) out.push(`${p + 1}Pの idx / id が保存されていません`);
  }

  // 同じスロットの重複を確認
  const idxs = d
    .slice(0, n)
    .map((s) => (s ? s.idx : null))
    .filter((v) => v !== null);
  if (new Set(idxs).size !== idxs.length) {
    out.push("同じコントローラーが複数のPに登録されています");
  }
  return out;
}

/* ==========================================================
   ■ 接続イベント機能
   ========================================================== */

/* ---- 機能限定の変数 ---- */
let cutF = null; // 切断されたときに呼ぶ関数（使う側が onCut で登録する）

/* ----------------------------------------------------------
   onCut(fn): 「割り当て済みのPのコントローラが抜けた」ときに呼ぶ関数を登録する
   fn は P の番号（0始まり）を受け取る。例: GP.onCut((p) => { ... });
   ---------------------------------------------------------- */
function onCut(fn) {
  cutF = fn;
}

/* ---- イベントリスナ ---- */
// 接続: 確認用のログだけ（読み取りは poll で拾えるので、ここで割り当てはしない）
window.addEventListener("gamepadconnected", (e) => {
  console.log("接続:", e.gamepad.id);
});

// 切断: 抜けたコントローラが、割り当て済みの P か調べる
window.addEventListener("gamepaddisconnected", (e) => {
  // e.gamepad.index はスロット番号。idx と id が両方合う P を探す（無ければ -1）
  const p = pls.findIndex(
    (s) => s.idx === e.gamepad.index && s.id === e.gamepad.id,
  );
  console.log("切断:", e.gamepad.id, "→ P", p);
  if (p === -1) return; // 参加者のコントローラでなければ何もしない
  rst(p); // 対象の割り当てを消す（ログイン情報は残る）
  if (cutF) cutF(p); // 使う側にPの番号を通知（ポップアップは使う側で出す）
});

/* ==========================================================
   ■ 選択人数機能
   ========================================================== */

/* ----------------------------------------------------------
   getTar(): 今の選択人数を返す
   ---------------------------------------------------------- */
function getTar() {
  return tarPls;
}

/* ----------------------------------------------------------
   setTar(n): 選択人数を変えて保存する。
   1〜MAX の整数以外は無視して false（HTMLの data-n が書き換えられても安全）
   ---------------------------------------------------------- */
function setTar(n) {
  if (!Number.isInteger(n) || n < 1 || n > MAX) return false;
  tarPls = n;
  try {
    sessionStorage.setItem(KEYT, String(n));
  } catch (e) {
    /* 保存できなくても画面は動かす */
    window.console.log("sessionStorage保存不可(人数)", e);
  }
  return true;
}

/* ==========================================================
   ■ ログイン状態機能
   認証そのものはサーバが行う。ここはその結果を持つだけ。
   ========================================================== */

/* ----------------------------------------------------------
   lgin(p, name, tok): ログイン成功後に、サーバから返った
   name と tok をPに紐づけて保存する
   ---------------------------------------------------------- */
function lgin(p, name, tok) {
  pls[p].name = name;
  pls[p].tok = tok;
  save();
}

/* ----------------------------------------------------------
   lout(p): Pをゲストに戻す（name=guest, tok=null）
   ---------------------------------------------------------- */
function lout(p) {
  pls[p].name = GST;
  pls[p].tok = null;
  save();
}

/* ----------------------------------------------------------
   pl(p): Pのログイン情報のコピーを返す { name, tok, guest }
   ※ 元の配列を直接触らせないよう、コピーで返す。
   ---------------------------------------------------------- */
function pl(p) {
  const s = pls[p];
  return { name: s.name, tok: s.tok, guest: s.tok === null };
}

