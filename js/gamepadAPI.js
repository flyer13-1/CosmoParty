/* ==========================================================
   gamepadAPI.js  コントローラ + ログイン状態の共通管理
   ES Module（export 形式）。グローバル変数は一切作らない。
   使う側のJSで読み込む:
     import * as GP from './gamepadAPI.js';
     GP.poll(); GP.live(0); ...
   ※ HTML側は <script type="module" src="使う側.js"> にすること。
   ※ file:// では module が動かない。localhost か HTTPS で開く
     （Gamepad API も同じ条件が必要なので追加の制約にはならない）。

   【設計メモ】
   ・自分ではループを回さない（setInterval / requestAnimationFrame を持たない）。
     ゲーム側のループが、フレームの頭で poll() を1回呼ぶ。
     → 「読む」と「使う」が同じフレームになり、ずれない。
   ・ページが変わると JS の変数は消えるので、
     Pごとの状態は sessionStorage に保存して、読み込み時に復元する。
   ・パスワードは絶対に保存しない。ログイン後に持つのは name と tok(トークン)だけ。
   ・tok が null の人は guest 扱い。
   ・p は 0始まり（0 = 1P, 1 = 2P, 2 = 3P, 3 = 4P）。
   ・変数名は4文字以内（Flyの指定）。
   ========================================================== */

"use strict"; //jsのモード

/* ---- 設定値 ---- */
const MAX = 4; // 最大人数
const KEY = "cpty_gp"; // sessionStorage のキー
const GST = "guest"; // ゲスト名

/* ---- 内部の状態 ---- */
let pls = lord(); // コントローラー[p]の記録 { idx, id, name, tok }
let snp = []; // 最新のコントローラ一覧

/* ----------------------------------------------------------
     c_gp(): 空のP状態を作る（未割り当て・ゲスト）
     ---------------------------------------------------------- */
function c_gp() {
  return { idx: null, id: null, name: GST, tok: null };
}

/* ----------------------------------------------------------
     lord(): sessionStorage から復元。無い/壊れていれば空の状態を返す
     ---------------------------------------------------------- */
function lord() {
  try {
    const d = JSON.parse(sessionStorage.getItem(KEY));
    if (Array.isArray(d) && d.length === MAX) return d;
  } catch (e) {
    /* 壊れていたら下で作り直す */
    alert("コントローラー情報が読めませんでした。");
    window.console.log("sessionStorageロード不可", e);
  }
  return Array.from({ length: MAX }, c_gp);
}

/* ----------------------------------------------------------
     save(): 今の状態を sessionStorage に保存（変更するたびに呼ぶ）
     ---------------------------------------------------------- */
function save() {
  try {
    sessionStorage.setItem(KEY, JSON.stringify(pls));
  } catch (e) {
    /* 保存できなくても画面は動かす */
    alert("コントローラー情報が保存できませんでした。");
    window.console.log("sessionStorage保存不可", e);
  }
}

/* ==========================================================
   コントローラ部分
   ========================================================== */

/* ----------------------------------------------------------
   poll(): コントローラの最新状態を1回だけ読んで、写しを更新する。
   ゲームのループの「フレームの頭」で毎回1回呼ぶこと。
   ※ Gamepadオブジェクトは「その瞬間の写し」なので使い回さず、毎回取り直す。
   ※ ブラウザの仕様で、ボタンを1回押すまで一覧が空のことがある。
   ---------------------------------------------------------- */
function poll() {
  const g = navigator.getGamepads ? navigator.getGamepads() : null;
  snp = g ? Array.from(g) : [];
  return snp;
}

/* ----------------------------------------------------------
   pad(p): Pに割り当て済みのコントローラ(最新の写し)を返す。無ければ null
   idx と id の両方が一致したものだけを採用（抜き差しで別機器に
   入れ替わったときの取り違え防止）。
   ---------------------------------------------------------- */
function pad(p) {
  const s = pls[p];
  if (s.idx === null) return null;
  const g = snp[s.idx];
  return g && g.connected && g.id === s.id ? g : null;
}

/* ----------------------------------------------------------
   live(p): Pのコントローラが今つながっているか（true/false）
   ---------------------------------------------------------- */
function live(p) {
  return pad(p) !== null;
}

/* ----------------------------------------------------------
   asg(p, idx): Pにコントローラ(idx番)を手動で割り当てる
   ---------------------------------------------------------- */
function asg(p, idx) {
  const g = snp[idx];
  if (!g) return false;
  pls[p].idx = idx;
  pls[p].id = g.id;
  save();
  return true;
}

/* ----------------------------------------------------------
   auto(): つながっているコントローラのうち、まだどのPにも
   割り当てられていないものを、空いている若いPから順に割り当てる。
   ※ 切断されたコントローラの割り当ては消さない。
     （新しいページを開いた直後は、ボタンを押すまで一覧が空になる。
       ここで消すと、ページ遷移のたびに割り当てが消えてしまうため）
     消したいときは rst() を使う。
   ---------------------------------------------------------- */
function auto() {
  poll();
  snp.forEach((g, i) => {
    if (!g || !g.connected) return;
    // すでに割り当て済みか確認
    const had = pls.some((s) => s.idx === i && s.id === g.id);
    if (had) return;
    // 空いている最初のPに入れる
    const p = pls.findIndex((s) => s.idx === null);
    if (p >= 0) {
      pls[p].idx = i;
      pls[p].id = g.id;
    }
  });
  save();
}

/* ----------------------------------------------------------
   chk(): 割り当て済みなのに、今つながっていないPの番号の配列を返す。
   空配列なら全員OK。→ 「ボタンを押してね」の表示判定に使う
   ---------------------------------------------------------- */
function chk() {
  const out = [];
  pls.forEach((s, p) => {
    if (s.idx !== null && !live(p)) out.push(p);
  });
  return out;
}

/* ----------------------------------------------------------
   rst(p): Pのコントローラ割り当てだけを消す。p を省略すると全員分
   （ログイン情報は消さない）
   ---------------------------------------------------------- */
function rst(p) {
  const f = (s) => {
    s.idx = null;
    s.id = null;
  };
  if (p === undefined) pls.forEach(f);
  else f(pls[p]);
  save();
}

/* ==========================================================
   ログイン状態部分
   認証そのものはサーバが行う。ここはその結果を持つだけ。
   ========================================================== */

/* ----------------------------------------------------------
   lgin(p, name, tok): ログイン成功後に、サーバから返った
   name と tok をPに紐づけて保存する
   ---------------------------------------------------------- */
function lgin(p, name, tok) {
  pls[p].name = name;
  pls[p].tok = tok;
  save();
}

/* ----------------------------------------------------------
   lout(p): Pをゲストに戻す（name=guest, tok=null）
   ---------------------------------------------------------- */
function lout(p) {
  pls[p].name = GST;
  pls[p].tok = null;
  save();
}

/* ----------------------------------------------------------
   pl(p): Pのログイン情報のコピーを返す { name, tok, guest }
   ※ 元の配列を直接触らせないよう、コピーで返す。
   ---------------------------------------------------------- */
function pl(p) {
  const s = pls[p];
  return { name: s.name, tok: s.tok, guest: s.tok === null };
}

/* ---- 公開する関数（export したものだけ外から使える） ----
   pls / snp / lord / save / c_gp などの内部の状態と関数は export しないので、
   読み込んだ側から直接書き換えられない。 */
export { MAX, poll, pad, live, asg, auto, chk, rst, lgin, lout, pl };
